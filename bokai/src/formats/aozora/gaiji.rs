/// `U+xxxx` inside an annotation body. Aozora also appends the 底本 page and
/// line (`U+25954、430-13`), which is why this is a search rather than a match.
static UNICODE_RE: LazyLock<Regex> =
    LazyLock::new(|| Regex::new(r"U\+([0-9A-Fa-f]{4,6})").unwrap());
/// A 面区点 code: plane, ku, ten. Written bare (`1-8-78`) for the JIS X 0213
/// symbol rows and after a 水準 label (`第3水準1-88-85`) for the kanji rows.
/// The trailing 底本 page-line reference has only two parts, so it cannot match.
static MEN_KU_TEN_RE: LazyLock<Regex> =
    LazyLock::new(|| Regex::new(r"([12])-(\d{1,2})-(\d{1,2})").unwrap());

/// Resolve the body of a `※［＃…］` annotation to the character it names.
pub fn resolve(body: &str) -> Option<Cow<'static, str>> {
    if let Some(caps) = UNICODE_RE.captures(body)
        && let Ok(cp) = u32::from_str_radix(&caps[1], 16)
        && let Some(ch) = char::from_u32(cp)
    {
        return Some(Cow::Owned(ch.to_string()));
    }
    let caps = MEN_KU_TEN_RE.captures(body)?;
    let plane: u16 = caps[1].parse().ok()?;
    let ku: u16 = caps[2].parse().ok()?;
    let ten: u16 = caps[3].parse().ok()?;
    if !(1..=94).contains(&ku) || !(1..=94).contains(&ten) {
        return None;
    }
    let key = plane * 10_000 + ku * 100 + ten;
    let idx = X0213.binary_search_by_key(&key, |(k, _)| *k).ok()?;
    Some(Cow::Borrowed(X0213[idx].1))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn resolves_men_ku_ten_kanji() {
        // 顳顬 (こめかみ) — the second kanji is 第3水準, so only the first can be
        // written literally and the second arrives as an annotation.
        assert_eq!(resolve("「需＋頁」、第3水準1-94-6").as_deref(), Some("顬"));
        // 第4水準 lives in plane 2.
        assert_eq!(
            resolve("「りっしんべん＋曷」、第4水準2-12-59").as_deref(),
            Some("愒")
        );
    }

    #[test]
    fn resolves_bare_symbol_codes() {
        assert_eq!(resolve("感嘆符疑問符、1-8-78").as_deref(), Some("\u{2049}"));
        assert_eq!(resolve("感嘆符二つ、1-8-75").as_deref(), Some("\u{203C}"));
        assert_eq!(
            resolve("濁点付き片仮名ワ、1-7-82").as_deref(),
            Some("\u{30F7}")
        );
        assert_eq!(resolve("アレフ、1-3-60").as_deref(), Some("\u{2135}"));
        assert_eq!(resolve("4分の3、1-9-21").as_deref(), Some("¾"));
    }

    #[test]
    fn unicode_form_wins_over_trailing_page_line() {
        // `430-13` is a 底本 page-line reference, not a 面区点 code.
        assert_eq!(
            resolve("「穴かんむり／石」、U+25954、430-13").as_deref(),
            Some("\u{25954}")
        );
    }

    #[test]
    fn prose_only_annotation_has_no_answer() {
        assert!(resolve("「くさかんむり／夷」").is_none());
        assert!(resolve("ここから2字下げ").is_none());
    }

    #[test]
    fn table_is_sorted_and_unique() {
        assert!(
            X0213.windows(2).all(|w| w[0].0 < w[1].0),
            "table must be sorted by key"
        );
    }
}
