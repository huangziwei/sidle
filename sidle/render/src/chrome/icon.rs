//! Icon artwork: each icon a run of [`Step`]s in a [`BOX`]-unit square.
//!
//! [`Step::Ink`] and [`Step::Ground`] open a shape and give it its colour.
//! Shapes fill in the order stated, each by the even-odd rule.

/// Side of the square [`Step`] coordinates lie in.
pub const BOX: f32 = 100.0;

/// One step of an outline, in [`BOX`] units.
#[derive(Debug, Clone, Copy, PartialEq)]
pub enum Step {
    /// Opens a shape in the ink colour.
    Ink,
    /// Opens a shape in the colour of the surface under the icon.
    Ground,
    Move(f32, f32),
    Line(f32, f32),
    /// A cubic curve: two control points, then the point reached.
    Curve(f32, f32, f32, f32, f32, f32),
    Close,
}

